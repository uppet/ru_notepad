#!/usr/bin/env python3
"""Validate reviewed UTF-8 catalogs and emit deterministic, embedded Ru data.

No runtime JSON parser, filesystem lookup, network or Python is required by the app.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('en', 'zh-CN', 'ja', 'ko', 'es', 'ru', 'it')
KEY = re.compile(r'[a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+\Z')


def pairs_unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'duplicate catalog key: {key}')
        result[key] = value
    return result


def placeholders(text):
    # The Ru formatter deliberately supports one ASCII digit, with no escaping,
    # field access, nested formatting, conversions or format specifications.
    tokens = re.findall(r'\{([0-9])\}', text)
    remainder = re.sub(r'\{[0-9]\}', '', text)
    if '{' in remainder or '}' in remainder:
        raise ValueError(f'only exact ASCII {{0}}..{{9}} placeholders are supported: {text!r}')
    return sorted(map(int, tokens))


def catalog(root=ROOT):
    result = {}
    files = sorted((root / 'locales').glob('*.json'))
    if not files:
        raise ValueError('no catalogs found')
    for path in files:
        data = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=pairs_unique)
        for key, messages in data.items():
            if not KEY.fullmatch(key) or key in result:
                raise ValueError(f'invalid or duplicate stable key: {key}')
            if set(messages) != set(LANGUAGES):
                raise ValueError(f'{key}: exactly seven languages are required')
            for language, value in messages.items():
                if not isinstance(value, str) or not value or '\0' in value or '\r' in value:
                    raise ValueError(f'{key}/{language}: expected nonempty NUL-free text')
                if key.startswith('file.filter.') and '|' in value:
                    raise ValueError(f'{key}/{language}: native filter separator is forbidden in labels')
                if placeholders(value) != placeholders(messages['en']):
                    raise ValueError(f'{key}/{language}: placeholder contract differs from English')
            result[key] = messages
    return result


def quote(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n').replace('\t', '\\t') + "'"


def render(data):
    rows = ['# Generated by tools/generate_i18n.py. Edit locales/*.json, then regenerate.',
            '# Flat primitive text values keep native ABI analysis bounded.', '目录 取 {']
    items = [(lang + ':' + key, data[key][lang]) for key in sorted(data) for lang in LANGUAGES]
    for index, (key, value) in enumerate(items):
        rows.append('    ' + quote(key) + ':' + quote(value) + (',' if index + 1 < len(items) else ''))
    rows.extend(['}.', ''])
    return '\n'.join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = catalog()
    expected = render(data)
    target = ROOT / 'src/i18n_catalog.ru'
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf-8') != expected:
            raise SystemExit('Generated Ru catalog is stale; run tools/generate_i18n.py')
    else:
        target.write_text(expected, encoding='utf-8')
    print(f'PASS: {len(data)} stable keys, {len(LANGUAGES)} complete languages, matching placeholders')


if __name__ == '__main__':
    main()
