def read_process_memory(process):
    """Read only this owned Popen handle. No process search, job, or settings."""
    require(os.name == 'nt', 'windows_memory_reader_required')
    import ctypes
    from ctypes import wintypes
    class Counters(ctypes.Structure):
        _fields_ = [('cb', wintypes.DWORD), ('PageFaultCount', wintypes.DWORD)] + [
            (name, ctypes.c_size_t) for name in ('PeakWorkingSetSize', 'WorkingSetSize',
            'QuotaPeakPagedPoolUsage', 'QuotaPagedPoolUsage', 'QuotaPeakNonPagedPoolUsage',
            'QuotaNonPagedPoolUsage', 'PagefileUsage', 'PeakPagefileUsage', 'PrivateUsage')]
    require(ctypes.sizeof(ctypes.c_void_p) == 8 and ctypes.sizeof(Counters) == 80, 'windows_memory_layout_mismatch')
    value = Counters(); value.cb = ctypes.sizeof(value)
    read = ctypes.WinDLL('psapi', use_last_error=True).GetProcessMemoryInfo
    read.argtypes = [wintypes.HANDLE, ctypes.POINTER(Counters), wintypes.DWORD]
    read.restype = wintypes.BOOL
    if not read(wintypes.HANDLE(int(process._handle)), ctypes.byref(value), value.cb):
        raise ProcessMemoryReadError('process_memory_read_failed')
    return dict(zip(MEMORY_METRICS, (value.PrivateUsage, value.WorkingSetSize,
                                   value.PeakWorkingSetSize, value.PeakPagefileUsage)))


