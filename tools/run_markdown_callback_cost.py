def generated_regions(code, version):
    require(isinstance(code, str) and code and isinstance(version, str) and
            re.fullmatch(r'[0-9]+(?:\.[0-9]+)+', version) is not None, 'generated_identity_empty')
    banner = BANNER.format(version)
    require(code.startswith(banner) and code.count(banner) == 1, 'generator_banner_mismatch')
    require(all(code.count(marker) == 1 for marker in (RUNTIME_START, THUNKS_START, MODULE_START)),
            'generated_region_boundary_mismatch')
    start, end, app = (code.index(marker) for marker in (RUNTIME_START, THUNKS_START, MODULE_START))
    require(start >= len(banner) and start < end < app, 'generated_region_order')
    require(code[len(banner):start] in ('', '#define RU_ENABLE_MODULO 1\n'), 'generated_prefix_mismatch')
    return {'generator_banner': (0, len(banner)), 'runtime': (start, end)}


def validate_generated_delta(old, new, approval, versions):
    """Reconstruct every byte in one pass; never strip runtime or use patterns."""
    validate_approval(approval)
    require(versions == COMPILER_VERSIONS, 'compiler_version_schema')
    regions = {name: generated_regions(code, versions[name]) for name, code in (('old', old), ('new', new))}
    ranges = {'old': [], 'new': []}
    for pair in approval['replacements']:
        scope = pair['scope']
        for name, code in (('old', old), ('new', new)):
            literal = pair[name]
            require(code.find(literal) >= 0 and code.find(literal) == code.rfind(literal), 'delta_literal_not_unique')
            at = code.index(literal); finish = at + len(literal)
            begin, end = regions[name][scope]
            require(begin <= at < finish <= end, 'delta_outside_scope')
            if scope == 'generator_banner':
                require(literal == BANNER.format(versions[name]) and at == 0 and finish == end,
                        'delta_banner_not_exact')
            require(all(finish <= a or at >= b for a, b, _ in ranges[name]), 'delta_pairs_overlap')
            ranges[name].append((at, finish, pair))
    cursor = 0
    pieces = []
    for begin, end, pair in sorted(ranges['old'], key=lambda item: item[0]):
        pieces.extend((old[cursor:begin], pair['new']))
        cursor = end
    pieces.append(old[cursor:])
    require(''.join(pieces) == new, 'unapproved_generated_change')
    # Explicitly protect signature generation, trampolines and application bodies.
    require(old[regions['old']['runtime'][1]:] == new[regions['new']['runtime'][1]:],
            'generated_application_or_thunks_changed')
    return {'exact_approved_delta': True, 'replacement_count': len(approval['replacements']),
            'application_and_thunks_identical': True,
            'protected_suffix_sha256': hashlib.sha256(old[regions['old']['runtime'][1]:].encode()).hexdigest()}


def compiler_identity(root, pin):
    require(git(root, 'rev-parse', 'HEAD') == pin['commit'] and
            git(root, 'rev-parse', 'HEAD^{tree}') == pin['tree'] and
            git(root, 'status', '--porcelain', '--untracked-files=all') == '', 'compiler_pin_mismatch')
    init = root / 'rulang/__init__.py'
    require(init.is_file() and not init.is_symlink(), 'compiler_version_missing_or_linked')
    values = [n.value for n in ast.parse(init.read_text(encoding='utf-8')).body
              if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == '__version__' for t in n.targets)]
    require(len(values) == 1 and isinstance(values[0], ast.Constant) and
            isinstance(values[0].value, str) and re.fullmatch(r'[0-9]+(?:\.[0-9]+)+', values[0].value),
            'compiler_version_invalid')
    return {**pin, 'version': values[0].value}


def graph_identity(graph, ru_root):
    result = {}
    for raw in graph:
        path = Path(raw).resolve()
        # Compiler roots may themselves be nested under app/.ci. Match stdlib first.
        if path.is_relative_to(ru_root / 'rulang/stdlib'):
            name = 'compiler-stdlib/' + path.relative_to(ru_root / 'rulang/stdlib').as_posix()
        elif path.is_relative_to(ROOT / 'src') or path.is_relative_to(ROOT / 'tests'):
            name = 'app/' + path.relative_to(ROOT).as_posix()
        else:
            raise ResearchError('graph_source_outside_roots')
        require(name not in result and not Path(raw).is_symlink(), 'graph_source_duplicate_or_linked')
        result[name] = sha(path)
    require(bool(result), 'graph_source_empty')
    return result

def instrument_generated(code: str, callback_id: str, reader_id: str, diagnostics=None) -> str:
    """Exact reversible counter hooks plus optional fixed scalar live diagnostics."""
    diagnostics = {} if diagnostics is None else diagnostics
    require(not diagnostics or set(diagnostics) == {'reset', 'peak', 'size', 'samples'}, 'diagnostic_ids_schema')
    names = [callback_id, reader_id, *diagnostics.values()]
    require(all(isinstance(name, str) and re.fullmatch(r'ru_function_[0-9]+', name) for name in names),
            'invalid_function_id')
    require(len(set(names)) == len(names), 'duplicate_function_id')
    require('ru_md_research_' not in code, 'already_instrumented')
    header = lambda name: f'static Val {name}(Env *global, Val self, int call_line, Val *args) {{\n'
    for name in names:
        require(code.count(header(name)) == 1, 'callback_or_stub_definition_mismatch')
    require(code.count('#include <stdint.h>\n') == 1, 'stdint_include_mismatch')
    declarations = ('static uint64_t ru_md_research_entries;\n'
                    'static int ru_md_research_overflow;\n')
    if diagnostics:
        declarations += ('static uint64_t ru_md_research_live_peak, ru_md_research_live_samples;\n'
                         'static int ru_md_research_live_active, ru_md_research_live_overflow;\n')
    entry = ('    if (ru_md_research_entries == UINT64_MAX) ru_md_research_overflow = 1;\n'
             '    else ++ru_md_research_entries;\n')
    ignored = '    (void)global; (void)self; (void)call_line; (void)args;\n'
    reader = ''
    if diagnostics:
        reader += ("    if (ru_md_research_live_active) {\n"
                   "        if (ru_md_research_live_samples == UINT64_MAX || ru_live > UINT64_C(9007199254740991))\n"
                   "            ru_md_research_live_overflow = 1;\n"
                   "        else {\n"
                   "            ++ru_md_research_live_samples;\n"
                   "            if (ru_live > ru_md_research_live_peak) ru_md_research_live_peak = ru_live;\n"
                   "        }\n    }\n")
    reader += ('    if (ru_md_research_overflow || ru_md_research_entries > UINT64_C(9007199254740991))\n'
               '        return v_num(-1.0);\n'
               '    return v_num((double)ru_md_research_entries);\n')
    bodies = {reader_id: reader}
    if diagnostics:
        bodies.update({
            diagnostics['reset']: '    if (ru_md_research_live_active) return v_num(-1.0);\n'
                '    ru_md_research_live_peak = ru_md_research_live_samples = 0;\n'
                '    ru_md_research_live_overflow = 0; ru_md_research_live_active = 1;\n'
                '    return v_num(0.0);\n',
            diagnostics['peak']: '    if (ru_md_research_live_overflow || ru_md_research_live_samples != UINT64_C(3126))\n'
                '        return v_num(-1.0);\n    return v_num((double)ru_md_research_live_peak);\n',
            diagnostics['size']: '    return v_num((double)sizeof(RuHeap));\n',
            diagnostics['samples']: '    if (ru_md_research_live_overflow || ru_md_research_live_samples > UINT64_C(9007199254740991))\n'
                '        return v_num(-1.0);\n    return v_num((double)ru_md_research_live_samples);\n'})
    patched = code
    replacements = []
    for name, content in bodies.items():
        pattern = re.escape(header(name)) + r'.*?^}\n'
        matches = list(re.finditer(pattern, patched, re.MULTILINE | re.DOTALL))
        require(len(matches) == 1, 'stub_body_mismatch')
        match = matches[0]
        body = header(name) + ignored + content + '}\n'
        replacements.append((match.group(0), body))
        patched = patched[:match.start()] + body + patched[match.end():]
    patched = patched.replace('#include <stdint.h>\n', '#include <stdint.h>\n' + declarations, 1)
    patched = patched.replace(header(callback_id), header(callback_id) + entry, 1)
    restored = patched.replace(header(callback_id) + entry, header(callback_id), 1)
    restored = restored.replace('#include <stdint.h>\n' + declarations, '#include <stdint.h>\n', 1)
    for original, body in reversed(replacements):
        require(restored.count(body) == 1, 'instrumentation_restoration_mismatch')
        restored = restored.replace(body, original, 1)
    require(restored == code, 'instrumentation_not_exactly_reversible')
    return patched

