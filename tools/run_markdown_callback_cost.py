def is_digest(value, length):
    return (isinstance(value, str) and re.fullmatch('[a-f0-9]{' + str(length) + '}', value)
            is not None and value != '0' * length)


def validate_approval(value):
    require(isinstance(value, dict) and set(value) ==
            {'schema', 'old', 'new', 'approval_commit', 'replacements', 'expected_heap_size'}, 'approval_schema')
    require(type(value['schema']) is int and value['schema'] == 1, 'approval_schema')
    require(value['old'] == {'commit': OLD_COMMIT, 'tree': OLD_TREE}, 'old_compiler_pin_mismatch')
    require(isinstance(value['new'], dict) and set(value['new']) == {'commit', 'tree'} and
            all(is_digest(v, 40) for v in value['new'].values()) and
            all(value['new'][k] != value['old'][k] for k in ('commit', 'tree')) and
            is_digest(value['approval_commit'], 40), 'new_compiler_not_approved')
    layout = value['expected_heap_size']
    require(isinstance(layout, dict) and set(layout) == {'old', 'new'} and layout['old'] == 32 and
            all(type(v) is int and 0 < v <= 4096 for v in layout.values()), 'heap_layout_not_approved')
    pairs = value['replacements']
    require(isinstance(pairs, list) and 0 < len(pairs) <= 64, 'runtime_delta_not_approved')
    seen_old, seen_new = set(), set()
    for pair in pairs:
        require(isinstance(pair, dict) and set(pair) == {'scope', 'old', 'new'}, 'delta_pair_schema')
        require(pair['scope'] in ('runtime', 'generator_banner'), 'delta_scope')
        require(all(isinstance(pair[k], str) and pair[k] and '\r' not in pair[k]
                    and '\0' not in pair[k] for k in ('old', 'new')) and
                pair['old'] != pair['new'], 'delta_pair_empty_or_identity')
        require(pair['old'] not in seen_old and pair['new'] not in seen_new, 'delta_pair_duplicate')
        seen_old.add(pair['old']); seen_new.add(pair['new'])
    require(any(p['scope'] == 'runtime' for p in pairs), 'runtime_delta_not_approved')
    require(sum(p['scope'] == 'generator_banner' for p in pairs) <= 1, 'banner_pair_duplicate')
    return value


def unique_json_object(pairs):
    value = {}
    for key, item in pairs:
        require(key not in value, 'duplicate_json_key')
        value[key] = item
    return value


