#!/usr/bin/env python3
"""Generate pure Ru configuration from the reviewed, data-only language catalog."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'syntax/languages.json'
OUTPUT = ROOT / 'src/syntax_catalog.ru'

def quote(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('\r', '\\r').replace('\n', '\\n').replace('\t', '\\t') + "'"

def value(v):
    if isinstance(v, str): return quote(v)
    if isinstance(v, bool): return '真' if v else '假'
    if isinstance(v, int): return str(v)
    if isinstance(v, list): return '[' + ','.join(value(x) for x in v) + ']'
    raise TypeError(type(v))

def generate(data):
    profiles = data['languages']
    ids = [p['id'] for p in profiles]
    if len(ids) != len(set(ids)): raise ValueError('duplicate language id')
    out = ['# Generated by tools/generate_syntax_catalog.py; edit syntax/languages.json.',
           '# Configuration only. No DLL calls, runtime parsing or user-file execution.',
           '算 语言们:', '    得 '+value(ids)+'.', '法']
    functions = [('名称','name',''), ('词法器','lexer',''), ('词法号','lexer_id',0),
                 ('关键词','keywords',[]), ('性质','properties',[]),
                 ('色号','style_ids',[]), ('色值','style_colors',[]), ('可折叠','fold',False)]
    for name,key,default in functions:
        # Opaque map lookup keeps the native ABI planner from enumerating every
        # keyword/style across all languages as possible FFI descriptor values.
        out += [name+'表 取 {']
        out += ['    '+quote(row['id'])+':'+value(row[key])+(',' if i+1<len(profiles) else '')
                for i,row in enumerate(profiles)]
        out += ['}.','算 '+name+' 语言 为 句:',
                '    果 取 '+name+'表 其 查 语言.',
                '    若 果 == 空 则 得 '+value(default)+'. 然',
                '    得 果.','法']
    out += ['算 有语言 语言 为 句:', '    得 (名称 语言) != '+quote('')+'.', '法']
    for name,key,default in [('后缀','extensions','plain'),('文件名','filenames','')]:
        out += ['算 '+name+' 文 为 句:']
        for ext,lang in sorted(data[key].items()):
            out += ['    若 文 == '+quote(ext)+' 则 得 '+quote(lang)+'. 然']
        out += ['    得 '+quote(default)+'.','法']
    return '\n'.join(out)+'\n'

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    text=generate(json.loads(DATA.read_text(encoding='utf-8')))
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != text: raise SystemExit('syntax catalog is stale')
    else: OUTPUT.write_text(text,encoding='utf-8',newline='\n')

if __name__ == '__main__': main()
